import type {CSSProperties, ReactNode} from 'react';
import clsx from 'clsx';
import Link from '@docusaurus/Link';
import type {Props} from '@theme/TOCItems/Tree';
import {useReadingProgress} from '../../components/ReadingProgress';
import styles from './styles.module.css';

type Node = Props['toc'][number];

function flatten(toc: readonly Node[]): Node[] {
  return toc.flatMap((heading) => [heading, ...flatten(heading.children)]);
}

export default function TOCProgressTree({toc, className, linkClassName, isChild}: Props): ReactNode {
  const {sections} = useReadingProgress();
  const activeId = flatten(toc).filter(({id}) => sections[id]?.started).at(-1)?.id;
  if (!toc.length) return null;

  function tree(nodes: readonly Node[], nested: boolean): ReactNode {
    if (!nodes.length) return null;
    return (
      <ul className={nested ? styles.nested : clsx(className, styles.tree)}>
        {nodes.map((heading) => {
          const progress = sections[heading.id]?.progress ?? 0;
          const active = heading.id === activeId;
          return (
            <li key={heading.id}>
              <div className={styles.row} data-active={active} data-complete={progress === 100}>
                <span className={styles.track} aria-hidden="true"><span style={{'--section-progress': `${progress}%`} as CSSProperties} /></span>
                <Link
                  to={`#${heading.id}`}
                  className={linkClassName ?? undefined}
                  aria-current={active ? 'location' : undefined}
                  // The heading HTML is generated by Docusaurus' trusted MDX compiler.
                  dangerouslySetInnerHTML={{__html: heading.value}}
                />
              </div>
              {tree(heading.children, true)}
            </li>
          );
        })}
      </ul>
    );
  }

  return tree(toc, Boolean(isChild));
}
